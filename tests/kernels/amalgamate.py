#!/usr/bin/env python3
"""Build the single-file amalgam variant of a kernel.

Usage: amalgamate.py <kernel-dir> <out-file>

Inlines every `mod name;` declaration recursively, preserving the
module tree, so crate:: and super:: paths keep their meaning. The
output is committed next to the multi-file kernel as <name>-amalgam;
regenerate it with this script after editing kernel sources. The
amalgam must produce byte-equal output to the multi-file kernel.
"""
import pathlib
import re
import sys

MOD_DECL = re.compile(
    r"(?m)^([ \t]*)(#\[path\s*=\s*\"([^\"]+)\"\]\s*\n[ \t]*)?(pub(?:\(crate\))?\s+)?mod\s+(\w+)\s*;"
)


def resolve(current: pathlib.Path, name: str, path_attr: str | None) -> pathlib.Path:
    if current.name in ("mod.rs", "main.rs", "lib.rs"):
        base = current.parent
    else:
        base = current.parent / current.stem
    if path_attr is not None:
        # Empirically (and as rustc resolves it in these kernels): a
        # path attribute is relative to the directory of the file that
        # holds the mod item.
        return current.parent / path_attr
    for cand in (base / f"{name}.rs", base / name / "mod.rs"):
        if cand.exists():
            return cand
    raise SystemExit(f"cannot resolve mod {name} from {current}")


def inline(path: pathlib.Path, seen: tuple[pathlib.Path, ...]) -> str:
    if path in seen:
        raise SystemExit(f"module cycle at {path}")
    # The committed amalgams are UTF-8 with LF. Windows' locale encoding
    # (cp1252) rejects bytes in the kernel sources, and text mode would
    # write CR LF.
    text = path.read_text(encoding="utf-8")

    def repl(m: re.Match) -> str:
        indent, _attr, path_attr, vis, name = m.groups()
        child = resolve(path, name, path_attr)
        body = inline(child, seen + (path,))
        vis = vis or ""
        return f"{indent}{vis}mod {name} {{\n{body}\n{indent}}}"

    return MOD_DECL.sub(repl, text)


def main() -> None:
    kernel = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    root = kernel / "src" / "main.rs"
    header = (
        "// Single-file amalgam of the "
        + kernel.name
        + " kernel. Generated by\n"
        "// tests/kernels/amalgamate.py from ../"
        + kernel.name
        + "/src; do not edit by\n"
        "// hand. Regenerate after editing the multi-file kernel.\n\n"
    )
    body = inline(root, ())
    out.parent.mkdir(parents=True, exist_ok=True)
    text = (header + body).replace("\r\n", "\n").replace("\r", "\n")
    out.write_bytes(text.encode("utf-8"))
    print(f"wrote {out} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
